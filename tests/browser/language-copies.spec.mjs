import {test, expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import JSZip from 'jszip';
import {selectContext, clickVisible, settled} from './workspace-controls.mjs';
import {artifactPath} from './artifacts.mjs';

// block-language-contract 4.3: new copies declare API v3 and read without the
// internal bridge; copies saved before the change keep their text and result.
test.setTimeout(240000);
// A run restarts the session; a read during that instant is retried by the poll.
const scene = page => settled(page => page.evaluate(() => studioProbe.request('snapshot')), page);
const capability = page => settled(page => page.evaluate(() => studioProbe.capabilityExecution.snapshot()), page);
const sphereX = async page => (await capability(page))?.entities.find(entity => entity.id === 'sphere')?.local.position.x;
const exported = async page => JSON.parse(await page.evaluate(() => studioProbe.project.export()));
const bridge = /\bGG\.|\bctx\b|\bawait\b|\bgg_/;

async function open(page) {
  await page.goto('/');
  await page.waitForFunction(() => Boolean(window.studioProbe?.project));
  await page.evaluate(() => studioProbe.project.ready());
  await expect(page.locator('#run-editor')).toBeEnabled();
}
async function acknowledge(page) { if (await page.locator('#dismiss-notices').isVisible()) await page.locator('#dismiss-notices').click(); }
async function download(page, name) {
  const pending = page.waitForEvent('download');
  await clickVisible(page.locator('#save-project'));
  const path = artifactPath(name);
  await (await pending).saveAs(path);
  return path;
}
async function reopen(browser, path) {
  const context = await browser.newContext();
  const page = await context.newPage();
  await open(page);
  await page.locator('#open-project').setInputFiles(path);
  await expect(page.locator('#recovery-notice')).toContainText('Proyecto abierto');
  return {context, page};
}
async function runDocument(page, x) {
  await selectContext(page, 'text');
  await clickVisible(page.locator('#run-document'));
  // Run prepares a new scene asynchronously; read it only once the event
  // program is active, rather than hiding loading or unrelated snapshot errors.
  await expect(page.locator('#text-run-status')).toHaveText('Documento activo · eventos disponibles', {timeout: 90000});
  await expect.poll(async () => (await scene(page)).x, {timeout: 90000}).toBe(x);
}

test('LCOPY-001: new 2D copies declare API v3, read without the bridge, run like blocks and reopen intact', async ({page, browser}) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await open(page);
  await selectContext(page, '2d');
  await clickVisible(page.locator('#run-editor'));
  await expect(page.locator('#status')).toHaveText('Bloques ejecutados');
  await expect.poll(async () => (await scene(page)).x).toBe(12);
  const copies = {};
  for (const language of ['javascript', 'python']) {
    await selectContext(page, '2d');
    await clickVisible(page.locator('#copy-' + language));
    const saved = (await exported(page)).authoring.textDocuments.at(-1);
    expect(saved.language).toBe(language);
    expect(saved.runtime.api).toBe('api3');
    expect(saved.source).not.toMatch(bridge);
    copies[language] = saved;
    await clickVisible(page.locator('#stop-result'));
    await expect.poll(async () => (await scene(page)).x).toBe(0);
    await runDocument(page, 12);
  }
  const path = await download(page, 'language-copies-2d.ggproj');
  const manifest = JSON.parse(await (await JSZip.loadAsync(await readFile(path))).file('manifest.json').async('string'));
  expect(manifest.version).toBe(4);
  const reopened = await reopen(browser, path);
  const documents = (await exported(reopened.page)).authoring.textDocuments;
  for (const language of ['javascript', 'python']) {
    const restored = documents.find(document => document.id === copies[language].id);
    expect(restored.source).toBe(copies[language].source);
    expect(restored.runtime).toEqual(copies[language].runtime);
  }
  // The last copy stays selected after reopening; it runs without autorun first.
  expect((await scene(reopened.page)).x).toBe(0);
  await runDocument(reopened.page, 12);
  await reopened.context.close();
  expect(errors).toEqual([]);
});

test('LCOPY-002: a 3D copy saved with API2 keeps its text, its API and its result after reopening', async ({page, browser}) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await open(page);
  await selectContext(page, 'scene3d');
  await clickVisible(page.getByRole('button', {name: 'Añadir escena 3D', exact: true}));
  await expect(page.locator('#scene3d-program')).toBeVisible();
  await acknowledge(page);
  // The copy a project held before the change: generated by the API2 generator,
  // with no declared API, selected by the 3D context in JavaScript mode.
  const legacy = await page.evaluate(async () => {
    const {createGeneratedCapabilityDocument} = await import(new URL('./app/generated-capability-source.mjs', location.href).href);
    const ir = studioProbe.capabilityUI.get('scene3d').blockEditor.program();
    const {document} = createGeneratedCapabilityDocument(ir, 'javascript', {name: 'Copia API2'});
    const project = JSON.parse(await studioProbe.project.export());
    project.authoring.textDocuments.push(document);
    Object.assign(project.capabilities.config['gg.3d-basic'], {mode: 'javascript', selectedTextDocumentId: document.id});
    await studioProbe.project.open(JSON.stringify(project));
    return document;
  });
  expect(legacy.source).toMatch(/GG\.context|await ctx\./);
  expect(legacy.runtime?.api).toBeUndefined();
  await acknowledge(page);
  await selectContext(page, 'scene3d');
  await clickVisible(page.getByRole('button', {name: 'Ejecutar escena 3D', exact: true}));
  await expect.poll(() => sphereX(page), {timeout: 60000}).toBe(1);
  await clickVisible(page.locator('#stop-result'));
  const path = await download(page, 'language-copies-api2.ggproj');
  const reopened = await reopen(browser, path);
  const restored = (await exported(reopened.page)).authoring.textDocuments.find(document => document.id === legacy.id);
  expect(restored.source).toBe(legacy.source);
  expect(restored.runtime?.api).toBeUndefined();
  await acknowledge(reopened.page);
  await selectContext(reopened.page, 'scene3d');
  await clickVisible(reopened.page.getByRole('button', {name: 'Ejecutar escena 3D', exact: true}));
  await expect.poll(() => sphereX(reopened.page), {timeout: 60000}).toBe(1);
  await reopened.context.close();
  expect(errors).toEqual([]);
});
